/** плотность для перевода мл → г */
const DENSITY: Record<string, number> = { 'молоко 2,5%': 1.03, 'оливковое масло': 0.92, 'растительное масло': 0.92, 'соевый соус': 1.15, 'винный уксус': 1.01, 'вода': 1 };

export function nutrFor(name: string): Nutr | null {
  const v = T[name.toLowerCase()];
  return v ? { kcal: v[0], p: v[1], f: v[2], c: v[3], fib: v[4] } : null;
}

export function gramsOf(name: string, amount: number, unit?: string): number | null {
  if (unit === 'г') return amount;
  if (unit === 'мл') return amount * (DENSITY[name.toLowerCase()] ?? 1);
  return null;
}


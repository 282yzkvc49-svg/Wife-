const RULES: [ShopCategory, RegExp][] = [
  ['frozen', /заморож/],
  ['sauces', /соус|горчиц|уксус|масло (растит|олив|подсолн)|растительное масло|оливковое масло|^соль|паприк|зира|корица|специ|перец молот|чёрный перец|терияки|мёд|мед\b|варенье/],
  ['bread', /хлеб|тост|лаваш|хлебц|батон|багет/],
  ['dairy', /молок|сливк|сыр|творог|йогурт|кефир|сметан|яйц|яйца|масло сливоч|сливочное масло/],
  ['meat', /кур|индей|говяд|свинин|тилапи|минтай|хек|треск|лосос|форел|креветк|рыб|тунец|фарш/],
  ['grocery', /макарон|греч|рис|чечевиц|нут|фасол|булгур|овсян|фунчоз|мука|кунжут|орех|миндаль|семечк|в собственном соку|томатная паста|консерв|вялен/],
  ['veg', /морков|лук|чеснок|помидор|томат|огур|перец|кабач|баклажан|брокколи|шпинат|зелен|укроп|петрушк|батат|картоф|яблок|банан|ягод|груш|гриб|шампиньон|авокадо|капуст|салат|клубник|апельсин|мандарин|киви/],
];

export function categorize(name: string): ShopCategory {
  const n = name.toLowerCase().replace(/ё/g, 'е');
  for (const [cat, re] of RULES) if (re.test(n) || re.test(name.toLowerCase())) return cat;
  return 'other';
}

